# 2026-09-27 收緊「唔好問准」嗰段：實測仍然會先問一句先肯查
# （見下面 _GUESS_RULE 嘅由來）。
#
# 2026-09-27 晚再加一段「唔好講完『等我查下』就收工」。掃 state.db：
# 助手講咗會查、但嗰一轉 `tool_calls` 係空嘅，有 **13 次**（09-26～09-27，
# 只 match 幾個關鍵詞，所以係下限）。最離譜係 session d84a1d4f（20:24–20:26）：
#
#   [1] 20:24:52「你係想考我，定係真係想知原文？我幫你查下先」 tool_calls 空
#   [5] 20:25:45「等我查下」                                   tool_calls 空
